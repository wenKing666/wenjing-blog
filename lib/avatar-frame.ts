/**
 * 头像框的类型定义。
 *
 * **故意单独放一个文件、不 import 任何东西。**
 *
 * 因为后台的表单和选择器是客户端组件，它们需要这个类型；
 * 而 `lib/content/frames.ts` 的依赖链里有 `node:fs`。
 * 客户端组件从那边 import 是个陷阱：今天的 `import type` 会被编译器完全擦除、
 * 看起来没事，但哪天有人顺手改成导入一个**值**，整个 fs 依赖链就会被打进
 * 浏览器包，构建报 `Code generation for chunk item errored`。
 *
 * 本站已经踩过一次同类的坑（`lib/project-status.ts` 就是为此拆出来的）。
 * 纯类型、纯常量和读文件逻辑分开放，这条线才守得住。
 */
export type AvatarFrame = {
  id: string;
  /** 图片地址，形如 /uploads/xxx.png */
  url: string;
  /** 显示名，取自上传时的原始文件名 */
  name: string;
  /**
   * 静态首帧缩略图的地址。
   *
   * 为什么需要它：库里 79% 是 APNG 动图，平均将近 1MB、有的上百帧。
   * 网格一页渲染 48 个就等于同时解码 48 个动图 —— 掉帧、闪烁、翻页卡。
   * 换成一个几十 KB 的静态首帧，渲染开销直接降一个数量级；
   * 只有**被选中那一张**才让它动起来（那时正好该看清它长什么样）。
   *
   * 按需生成：浏览到哪一页就给那一页补，不在上传时一次性算 2046 个。
   * 还没生成出来的框会回落到动图本体，功能不受影响。
   */
  thumb?: string;
};
